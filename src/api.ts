import { invoke } from "@tauri-apps/api/core";
import type {
  AssetDefinition,
  ConnectionDefinition,
  CoreCatalog,
  CoreInstallResult,
  CoreController,
  ImportPreview,
  LibraryAsset,
  LibraryEntry,
  LifecycleCommandResult,
  MemberSettings,
  Variant,
  VariantPorts,
  ProcessSnapshot,
  ProjectCheck,
  Workspace,
  WorkspaceSnapshot,
} from "./types";

export const api = {
  snapshot: () => invoke<WorkspaceSnapshot>("get_snapshot"),
  startAsset: (assetId: string) => invoke<ProcessSnapshot>("start_asset", { assetId }),
  stopAsset: (assetId: string) => invoke<ProcessSnapshot[]>("stop_asset", { assetId }),
  startCore: () => invoke<ProcessSnapshot>("start_core_controller"),
  stopCore: () => invoke<ProcessSnapshot[]>("stop_core_controller"),
  runLifecycle: (command: "start" | "stop" | "reset") => invoke<LifecycleCommandResult>("run_lifecycle_command", { command }),
  startAll: () => invoke<ProcessSnapshot[]>("start_all"),
  stopAll: () => invoke<ProcessSnapshot[]>("stop_all"),
  inspectDirectory: (path: string) => invoke<ImportPreview>("inspect_business_pack_directory", { path }),
  applyPreview: (preview: ImportPreview) => invoke<Workspace>("apply_import_preview", { preview }),
  catalog: () => invoke<CoreCatalog>("get_core_catalog"),
  saveCatalog: (catalog: CoreCatalog) => invoke<CoreCatalog>("save_core_catalog", { catalog }),
  installCore: (version: string) => invoke<CoreInstallResult>("install_approved_core", { version }),
  ingestBridgeLine: (connectionId: string, line: string) => invoke<void>("ingest_bridge_monitor_line", { connectionId, line }),
  recordHeartbeat: (connectionId: string, message: string) => invoke<void>("record_manual_communication_event", { connectionId, message }),
  selectProject: (projectId: string) => invoke<void>("select_project", { projectId }),
  createProject: (name: string) => invoke<string>("create_project", { name }),
  importV1Workspace: (path: string, replace: boolean) => invoke<string>("import_v1_workspace", { path, replace }),
  clearStoreWarnings: () => invoke<void>("clear_store_warnings"),
  checkProject: () => invoke<ProjectCheck>("check_project"),
  acceptMemberChanges: (projectId: string, revisions: Record<string, string>) => invoke<ProjectCheck>("accept_member_changes", { projectId, revisions }),
  library: () => invoke<LibraryEntry[]>("get_library"),
  saveLibraryAsset: (asset: LibraryAsset, baseId: string | null, projectId: string | null, applyMemberIds: string[]) => invoke<string>("save_library_asset", { asset, baseId, projectId, applyMemberIds }),
  deleteLibraryAsset: (assetId: string) => invoke<void>("delete_library_asset", { assetId }),
  inspectVariant: (variant: Variant) => invoke<VariantPorts>("inspect_variant", { variant }),
  updateMember: (projectId: string, expected: MemberSettings, member: MemberSettings) => invoke<void>("update_member", { projectId, expected, member }),
  setMemberAsset: (projectId: string, memberId: string, expectedAssetId: string, expectedVariantId: string, assetId: string, variantId: string) => invoke<void>("set_member_asset", { projectId, memberId, expectedAssetId, expectedVariantId, assetId, variantId }),
  removeMember: (projectId: string, expected: MemberSettings) => invoke<void>("remove_member", { projectId, expected }),
  previewAddMember: (projectId: string, member: MemberSettings) => invoke<ProjectCheck>("preview_add_member", { projectId, member }),
  addMember: (projectId: string, member: MemberSettings, shownRevision: string | null) => invoke<void>("add_member", { projectId, member, shownRevision }),
  renameProject: (projectId: string, expected: string, name: string) => invoke<void>("rename_project", { projectId, expected, name }),
  setCoreController: (projectId: string, expected: CoreController | null, controller: CoreController | null) => invoke<void>("set_core_controller", { projectId, expected, controller }),
};

export function newConnection(): ConnectionDefinition {
  return {
    id: crypto.randomUUID(),
    source: "source",
    destination: "destination",
    label: "手動接続",
    transport: "unknown",
    pdu_names: [],
    endpoint_config: null,
    details: {},
    source_asset_id: null,
    destination_asset_id: null,
    owner_asset_id: null,
  };
}
